import hashlib, json, os, shutil, subprocess, re
from pathlib import Path
import sumolib
import xml.etree.ElementTree as ET
from functools import lru_cache

ROOT = Path(__file__).resolve().parents[1]
DATA = Path(os.environ.get('CITYLAB_DATA', ROOT / 'data'))
DATA.mkdir(parents=True, exist_ok=True)

def binary(name):
    found = shutil.which(name)
    if found: return found
    import sumo
    candidate = Path(sumo.__file__).parent / 'bin' / name
    if candidate.exists(): return str(candidate)
    raise RuntimeError(f'{name} is unavailable. Install requirements.txt; no substitute engine is used.')

def ensure_synthetic():
    folder = DATA / 'networks' / 'synthetic'
    folder.mkdir(parents=True, exist_ok=True)
    net = folder / 'network.net.xml'
    bundled=ROOT/'examples/synthetic/network.net.xml'
    if not net.exists() and bundled.exists():
        shutil.copyfile(bundled,net)
    if not net.exists():
        nodes = []
        edges = []
        for y in range(4):
            for x in range(4):
                i=f'n{x}{y}'
                nodes.append(f'<node id="{i}" x="{x*240}" y="{y*240}" type="{ "traffic_light" if x in (1,2) and y in (1,2) else "priority"}"/>')
                for dx,dy in [(1,0),(0,1)]:
                    if x+dx<4 and y+dy<4:
                        j=f'n{x+dx}{y+dy}'
                        for a,b in [(i,j),(j,i)]:
                            edges.append(f'<edge id="{a}_{b}" from="{a}" to="{b}" numLanes="1" speed="11.11" allow="passenger bus"/>')
        (folder/'nodes.xml').write_text('<nodes>'+''.join(nodes)+'</nodes>')
        (folder/'edges.xml').write_text('<edges>'+''.join(edges)+'</edges>')
        subprocess.run([binary('netconvert'),'--node-files',str(folder/'nodes.xml'),'--edge-files',str(folder/'edges.xml'),'--output-file',str(net),'--no-turnarounds','true','--tls.default-type','static','--tls.yellow.time','3','--tls.allred.time','1','--lefthand','true'],check=True,capture_output=True)
    return net

def net_path(identifier='synthetic'):
    if not re.fullmatch(r'[a-zA-Z0-9_-]+',identifier): raise ValueError('Invalid network identifier')
    if identifier=='synthetic': return ensure_synthetic()
    p=DATA/'networks'/identifier/'network.net.xml'
    if not p.exists(): raise ValueError('Network not found. Import an OSM extract first.')
    return p

def describe(identifier='synthetic'):
    path = net_path(identifier)
    return _describe(identifier, path.stat().st_mtime_ns, path.stat().st_size)

